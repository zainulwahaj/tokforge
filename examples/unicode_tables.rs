//! Capture how the Hugging Face ByteLevel pre-tokenizer's Oniguruma regex classifies every
//! Unicode scalar, and print it as Rust range tables for `src/bytelevel/unicode_tables.rs`.
//!
//!     cargo run --release --example unicode_tables > src/bytelevel/unicode_tables.rs
//!
//! Classification is observed, not copied from a Unicode data file, so the tables match the
//! exact `onig_sys` build in `Cargo.lock` (`\p{L}`, `\p{N}` and `\s` as that regex engine sees
//! them). `tests/bytelevel.rs` re-derives a sample and fails if the committed tables drift.
use std::io::Write;

use tokenizers::{
    pre_tokenizers::{
        byte_level::ByteLevel,
        split::{Split, SplitPattern},
    },
    tokenizer::{
        normalizer::SplitDelimiterBehavior, OffsetReferential, OffsetType, PreTokenizedString,
        PreTokenizer,
    },
};

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Class {
    Letter,
    Number,
    Whitespace,
    Other,
}

/// Classify one scalar by the number of regex splits around it: `a<c>a` stays one split only
/// for a letter, `1<c>1` only for a number, and `!<c>!` stays one split for any other
/// non-whitespace scalar, so a whitespace scalar is the remaining three-split case.
pub fn classify(pre: &ByteLevel, c: char) -> Class {
    if splits(pre, &format!("a{c}a")) == 1 {
        Class::Letter
    } else if splits(pre, &format!("1{c}1")) == 1 {
        Class::Number
    } else if splits(pre, &format!("!{c}!")) == 1 {
        Class::Other
    } else {
        Class::Whitespace
    }
}

fn splits(pre: &ByteLevel, text: &str) -> usize {
    let mut pretokenized = PreTokenizedString::from(text);
    pre.pre_tokenize(&mut pretokenized).unwrap();
    pretokenized
        .get_splits(OffsetReferential::Original, OffsetType::Byte)
        .len()
}

pub fn ranges(pre: &ByteLevel, class: Class) -> Vec<(u32, u32)> {
    let mut ranges: Vec<(u32, u32)> = Vec::new();
    for code in 0..=char::MAX as u32 {
        let Some(c) = char::from_u32(code) else {
            continue;
        };
        if classify(pre, c) != class {
            continue;
        }
        match ranges.last_mut() {
            Some(last) if last.1 + 1 == code => last.1 = code,
            _ => ranges.push((code, code)),
        }
    }
    ranges
}

/// Scalars in a regex character class, as Oniguruma decides membership: a `Split` that removes
/// every match leaves nothing of a one-scalar text exactly when the scalar is in the class.
fn class_ranges(class: &str) -> Vec<(u32, u32)> {
    let split = Split::new(
        SplitPattern::Regex(class.to_owned()),
        SplitDelimiterBehavior::Removed,
        false,
    )
    .unwrap();
    let mut ranges: Vec<(u32, u32)> = Vec::new();
    let mut buffer = [0u8; 4];
    for code in 0..=char::MAX as u32 {
        let Some(c) = char::from_u32(code) else {
            continue;
        };
        let mut pretokenized = PreTokenizedString::from(&*c.encode_utf8(&mut buffer));
        split.pre_tokenize(&mut pretokenized).unwrap();
        let kept = pretokenized
            .get_splits(OffsetReferential::Original, OffsetType::Byte)
            .len();
        if kept != 0 {
            continue;
        }
        match ranges.last_mut() {
            Some(last) if last.1 + 1 == code => last.1 = code,
            _ => ranges.push((code, code)),
        }
    }
    ranges
}

fn write_table(out: &mut impl Write, name: &str, ranges: &[(u32, u32)]) {
    writeln!(out).unwrap();
    writeln!(out, "#[rustfmt::skip]").unwrap();
    writeln!(out, "pub(crate) static {name}: &[(u32, u32)] = &[").unwrap();
    for (start, end) in ranges {
        writeln!(out, "    (0x{start:04X}, 0x{end:04X}),").unwrap();
    }
    writeln!(out, "];").unwrap();
    eprintln!("{name}: {} ranges", ranges.len());
}

fn main() {
    let pre = ByteLevel::new(false, false, true);
    let out = std::io::stdout();
    let mut out = out.lock();
    writeln!(
        out,
        "//! Generated by `cargo run --release --example unicode_tables`; do not edit by hand."
    )
    .unwrap();
    writeln!(
        out,
        "//! Unicode scalar classes as the Oniguruma regex in the Hugging Face ByteLevel"
    )
    .unwrap();
    writeln!(
        out,
        "//! pre-tokenizer sees them (`\\p{{L}}`, `\\p{{N}}`, `\\s`), captured from the"
    )
    .unwrap();
    writeln!(
        out,
        "//! `onig_sys` build pinned in Cargo.lock. Each entry is an inclusive range."
    )
    .unwrap();
    for (name, class) in [
        ("LETTERS", Class::Letter),
        ("NUMBERS", Class::Number),
        ("WHITESPACE", Class::Whitespace),
    ] {
        write_table(&mut out, name, &ranges(&pre, class));
    }
    // The two letter-and-mark classes of the o200k_base pattern, taken verbatim from it.
    writeln!(out).unwrap();
    writeln!(
        out,
        r"// o200k `[\p{{Lu}}\p{{Lt}}\p{{Lm}}\p{{Lo}}\p{{M}}]` and `[\p{{Ll}}\p{{Lm}}\p{{Lo}}\p{{M}}]`."
    )
    .unwrap();
    write_table(
        &mut out,
        "O200K_UPPER",
        &class_ranges(r"[\p{Lu}\p{Lt}\p{Lm}\p{Lo}\p{M}]"),
    );
    write_table(
        &mut out,
        "O200K_LOWER",
        &class_ranges(r"[\p{Ll}\p{Lm}\p{Lo}\p{M}]"),
    );
}
